"""Backend «Pocket Coach»: всё, что импортируется.

Два подпакета, у обоих нет своего ``__init__.py`` (namespace-пакеты):

- ``domain`` — правила и методика, всё, что чем-то управляет. Ни SQL, ни HTTP,
  ни чтения файлов: данные приходят аргументами, шаблоны промптов и вызов
  модели берутся из ``data``, решения принимаются здесь. Хочешь понять, как
  устроен коуч, — читай эту папку.
- ``data`` — как данные приходят и уходят: SQLite, файлы рядом с базой, шаблоны
  промптов, HTTP к Claude. Ничего не решает: правила лежат в ``domain`` и
  вызываются отсюда, когда хранилищу нужно решение (например, что записать
  при ретрае).

Точка входа HTTP-сервера — ``backend/server.py`` рядом с пакетом, скрипты
таймеров — в ``infra/jobs/``, проза для модели — в ``prompts/``, тексты
баннеров — в ``resources/``; где всё это лежит, пакет знает через ``BACKEND_DIR``.
"""

from pathlib import Path

# Корень backend: локально backend/, на VPS /opt/trainer-miniapp/app. Здесь же
# лежат prompts/, resources/ и локальная data/ — всё, что код читает с диска.
BACKEND_DIR = Path(__file__).resolve().parent.parent
# Два файла, которые читает не модель, а клиент: каталог упражнений и тексты
# баннеров. Едут на прод вместе с кодом.
RESOURCES_DIR = BACKEND_DIR / "resources"
