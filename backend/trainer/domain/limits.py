"""Границы допустимого: что сервер принимает от клиента и от модели.

Словари меток, диапазоны и потолки собраны здесь, каждое число с объяснением,
откуда оно взялось. Логика, которая их применяет, живёт рядом с данными:
``rules`` (вход с iOS и из MCP), ``plan_validator`` (ответ модели),
``coach_features`` (что аналитика считает правдоподобным).

Порогов методики здесь нет намеренно: свежесть замеров, частота deload, недели
застоя — решения тренера, они лежат рядом со своей логикой и описаны в docs/.

Модули читают значения как ``limits.X``, а не ``from limits import X``: так
тест подменяет потолок одним ``mock.patch.object(limits, "X", ...)``, и подмену
видят все, кто на него смотрит.
"""

from __future__ import annotations

# --------------------------------------------------------------------------- #
# Метки, которые ставит атлет
# --------------------------------------------------------------------------- #
# Метка нагрузки записанной сессии. ``deload`` здесь есть: разгрузочную сессию
# атлет записывает как разгрузочную. Что-то другое или пусто — ``None``, в
# промпте это «без плана» (rules.normalize_load_type). Не путать с
# PLANNED_LOAD_TYPES: у плана от модели словарь короче.
LOGGED_LOAD_TYPES = ("heavy", "medium", "light", "deload")

# Тяжесть подхода со слов атлета. Грубее RIR, промпт тренера предпочитает RIR.
# Порядок — это порядок в тексте ошибки «must be one of easy, ok, hard».
ALLOWED_SET_EFFORTS = ("easy", "ok", "hard")

# Повторы в запасе (RIR) на подходе: 0 — отказ, 4 — совсем легко. Дальше атлет
# на глаз уже не различает, поэтому шкала короткая.
MIN_SET_RIR = 0
MAX_SET_RIR = 4

# --------------------------------------------------------------------------- #
# Замеры тела
# --------------------------------------------------------------------------- #
# Что вообще может быть весом тела человека. Вне этого — описка: вес с
# тренажёра, вбитый в поле взвешивания, — так у атлета в 77 кг появлялись
# замеры по 22 кг. Отсекается на записи, чтобы мусор не доехал ни до базы,
# ни до коуча.
MIN_BODY_WEIGHT_KG = 30.0
MAX_BODY_WEIGHT_KG = 400.0

# Что аналитика согласна считать весом ЭТОГО атлета: тренд, темп фазы и совет
# по калориям считаются только по таким записям. Уже границ записи намеренно:
# запись отсекает невозможное, аналитика — неправдоподобное для взрослого
# силовика. Это два разных вопроса, а не рассинхрон.
MIN_PLAUSIBLE_BODY_WEIGHT = 40.0
MAX_PLAUSIBLE_BODY_WEIGHT = 150.0

# Обхват талии — одна пара и для записи, и для аналитики. Здесь границы обязаны
# совпадать: принять замер и молча выбросить его из совета по калориям — значит
# показать в UI «сохранено», а коучу — «талии нет» и предупреждение о старом
# замере. Третья копия — TrainerStore.validWaistRange в iOS, её держат руками.
MIN_WAIST_CM = 50.0
MAX_WAIST_CM = 160.0

# Обхваты кроме талии, лентой: метрики цели из vision (рука, плечи, грудь) и
# протокол стратегии (шея, бедро, ягодицы, предплечье; рука — оба протокола,
# расслабленно и в напряжении). Ключ — на проводе и в базе, подпись — в
# промпте. Талия сюда не входит: у неё своя таблица, лимиты и матрица.
MEASUREMENT_KINDS: dict[str, str] = {
    "arm_relaxed": "рука расслабленно",
    "arm_flexed": "рука в напряжении",
    "forearm": "предплечье",
    "shoulders": "плечи",
    "chest": "грудь",
    "neck": "шея",
    "thigh": "бедро",
    "hips": "ягодицы",
}
# Одна пара границ на все обхваты: она отсекает описку (миллиметры, вес в
# поле обхвата), а правдоподобность конкретного обхвата — суждение атлета и
# тренера, не сервера. Уже талии снизу, потому что шея и предплечье меньше.
MIN_CIRCUMFERENCE_CM = 10.0
MAX_CIRCUMFERENCE_CM = 200.0

# --------------------------------------------------------------------------- #
# План от модели: границы здравого смысла, не методика
# --------------------------------------------------------------------------- #
# JSON-схема не умеет числовых диапазонов, поэтому ответ модели клампится после
# разбора (plan_validator). Это гигиена, а не методика: диапазоны повторов,
# размер сессии и шаги весов — суждение модели, и они сознательно не проверяются.
MAX_EXERCISES = 10
MAX_SETS_PER_EXERCISE = 12
MAX_REPS = 100
MAX_WEIGHT = 1000.0
# Через сколько дней тренировка: клампится в 0–4 молча, без репромпта.
MAX_REST_DAYS = 4

# Метка нагрузки в плане и enum в JSON-схеме ответа. ``deload`` здесь нет:
# разгрузка приходит модели флагом недели в контексте и выражается объёмом и
# весами по стратегии, а не меткой. Незнакомая метка в ответе становится ``medium``.
PLANNED_LOAD_TYPES = ("heavy", "medium", "light")

# --------------------------------------------------------------------------- #
# Снапшот совета внутри тренировки
# --------------------------------------------------------------------------- #
# Снапшот — копия совета, которую клиент прикладывает к тренировке ради
# статистики «факт против плана». Он best-effort: любая кривизна даёт None, и
# тренировка сохраняется без него. Упражнений и подходов в нём не больше, чем
# в плане, а повторы и вес клампятся шире, чем у плана: снапшот не проверяют
# на методику, он лишь не должен раздуть строку тренировки — отсюда и потолок
# в байтах.
MAX_RECOMMENDATION_SNAPSHOT_BYTES = 8192
MAX_SNAPSHOT_EXERCISES = MAX_EXERCISES
MAX_SNAPSHOT_SETS = MAX_SETS_PER_EXERCISE
SNAPSHOT_MAX_REPS = 1000
SNAPSHOT_MAX_WEIGHT = 10000.0
# Строковые поля снапшота обрезаются до этих длин (в символах).
SNAPSHOT_TEXT_LIMITS = {
    "name": 120,  # имя упражнения
    "source": 32,  # кто сгенерировал совет
    "model": 64,  # идентификатор модели
    "applied_at": 40,  # ISO-время, когда план применили
    "focus": 200,  # цель тренировки
}
